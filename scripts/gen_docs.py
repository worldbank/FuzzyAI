"""Generate docs/config-reference.md and docs/components.md from the code.

    python scripts/gen_docs.py

The config reference comes from the pydantic JSON schema of the pipeline document
(``deduplix.engine.config.config_json_schema``); the component catalogue comes from the
registry (``deduplix.engine.registry.list_components``). Do not edit the generated pages by hand.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from deduplix.engine.config import config_json_schema  # noqa: E402
from deduplix.engine.registry import KINDS, list_components  # noqa: E402

DOCS = ROOT / "docs"
BANNER = "<!-- Generated by scripts/gen_docs.py. Do not edit by hand. -->\n\n"

SECTION_HELP = {
    "normalize": "List of normalizers applied in order. Each entry is a name or a one-key mapping `{name: params}`.",
    "blocking": "List of blockers; their candidate pairs are unioned.",
    "compare": "Mapping `feature -> {fn: comparator_or_string_function, ...params}`. Each entry produces column `f_<feature>`.",
    "score": "One scorer, a name or `{name: params}`.",
    "route": "One router, a name or `{name: params}`.",
    "validate": "List of validators run on the pairs the router left for review.",
    "cluster": "One clusterer.",
    "consolidate": "One consolidator.",
    "hooks": "List of hooks.",
    "options": "Engine options.",
}


def _type_of(prop: Dict[str, Any], defs: Dict[str, Any]) -> str:
    if "$ref" in prop:
        return "object (" + prop["$ref"].split("/")[-1] + ")"
    if "anyOf" in prop:
        parts = [_type_of(p, defs) for p in prop["anyOf"]]
        return " or ".join(dict.fromkeys(parts))
    t = prop.get("type", "any")
    if t == "array":
        return "list of " + _type_of(prop.get("items", {}), defs)
    if t == "object":
        ap = prop.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return "mapping of " + _type_of(ap, defs)
        return "mapping"
    return str(t)


def _default_of(prop: Dict[str, Any]) -> str:
    if "default" in prop:
        return "`" + json.dumps(prop["default"]) + "`"
    if "default_factory" in prop:
        return "empty"
    return "empty"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def config_reference() -> str:
    schema = config_json_schema()
    defs = schema.get("$defs", {})
    out: List[str] = [BANNER, "# Config reference\n\n"]
    out.append(
        "A pipeline document is a YAML file (or a Python dict) loaded with "
        "`Pipeline.from_config(...)` or `load_pipeline(...)`. "
        + schema.get("description", "").replace("``", "`") + " "
        "Unknown top-level keys are rejected. `${NAME}` is replaced by the environment variable `NAME`.\n\n"
    )
    out.append("## Top-level keys\n\n| Key | Type | Default | Description |\n| --- | --- | --- | --- |\n")
    for key, prop in schema["properties"].items():
        out.append("| `%s` | %s | %s | %s |\n" % (
            key, _cell(_type_of(prop, defs)), _default_of(prop), _cell(SECTION_HELP.get(key, ""))))
    for name, d in defs.items():
        out.append("\n## `%s` keys\n\n| Key | Type | Default |\n| --- | --- | --- |\n" % name.lower())
        for key, prop in d.get("properties", {}).items():
            out.append("| `%s` | %s | %s |\n" % (key, _cell(_type_of(prop, defs)), _default_of(prop)))
    out.append("\nSee the [component catalogue](components.md) for the names and parameters "
                "that each section accepts.\n")
    out.append("\n## Raw JSON schema\n\n```json\n%s\n```\n" % json.dumps(schema, indent=2))
    return "".join(out)


def components_page() -> str:
    out: List[str] = [BANNER, "# Component catalogue\n\n"]
    out.append("Every registered component, by kind. Use the name in YAML (`name` or `{name: params}`) "
               "or in Python (`Pipeline(blockers=[{\"tfidf_char\": {\"top_n\": 20}}])`). "
               "Components from optional extras appear only when their dependencies are installed.\n\n")
    comps = list_components()
    for kind in KINDS:
        rows = [c for c in comps if c["kind"] == kind]
        if not rows:
            continue
        out.append("## %s\n\n| Name | Parameters | Description |\n| --- | --- | --- |\n" % (kind + "s"))
        for c in sorted(rows, key=lambda c: c["name"]):
            params = ", ".join("`%s`" % p for p in c.get("parameters", [])) or "none"
            out.append("| `%s` | %s | %s |\n" % (c["name"], params, _cell((c.get("doc") or "").replace("``", "`"))))
        out.append("\n")
    return "".join(out)


def main() -> None:
    DOCS.mkdir(exist_ok=True)
    (DOCS / "config-reference.md").write_text(config_reference(), encoding="utf-8")
    (DOCS / "components.md").write_text(components_page(), encoding="utf-8")
    print("wrote docs/config-reference.md and docs/components.md")


if __name__ == "__main__":
    main()
